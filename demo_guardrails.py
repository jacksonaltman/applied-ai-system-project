"""Reproducible, offline demo of the guardrails. Run: python demo_guardrails.py

Feeds the full pipeline (retrieve -> prompt -> model -> validate) a SCRIPTED model reply
that mixes good and bad tasks, so you can see exactly what the guardrails accept and reject.
No API key or network is used; the model reply below is written by hand, not generated by an AI.
"""
import json
import logging

import ai_agent
from pawpal_system import Pet, Task
from datetime import datetime

logging.getLogger("pawpal").addHandler(logging.NullHandler())

pet = Pet("Biscuit", "labrador", species="dog", age_years=0.5)
pet.add_task(Task("Evening play", datetime(2099, 1, 1, 18, 0)))  # already scheduled

SCRIPTED_REPLY = {"tasks": [
    {"description": "Morning meal", "start": "07:00", "duration": 15, "frequency": "daily", "priority": "high", "source": "dog_young", "reason": "3 meals a day"},
    {"description": "Potty break", "start": "09:30", "duration": 10, "frequency": "daily", "priority": "high", "source": "dog_young", "reason": "after meals"},
    {"description": "Evening play", "start": "18:00", "duration": 20, "frequency": "daily", "priority": "medium", "source": "dog_young", "reason": "play"},
    {"description": "Teleport home", "start": "25:99", "duration": 10, "frequency": "daily", "priority": "low", "source": "dog_young", "reason": "bad time"},
    {"description": "Marathon run", "start": "10:00", "duration": 0, "frequency": "daily", "priority": "high", "source": "dog_young", "reason": "bad duration"},
    {"description": "Raw diet", "start": "12:00", "duration": 10, "frequency": "daily", "priority": "low", "source": "invented_guide", "reason": "not retrieved"},
    {"description": "Nap time", "start": "14:00", "duration": 30, "frequency": "hourly", "priority": "low", "source": "dog_young", "reason": "bad frequency"},
]}

print("INPUT pet:", pet.name, pet.species, pet.breed, f"{pet.age_years}y", "| existing tasks:", [t.description for t in pet.tasks])
result = ai_agent.suggest_tasks(pet, llm=lambda prompt, model: json.dumps(SCRIPTED_REPLY))
print("RETRIEVED guides:", [d.id for d in result.docs])
print(f"MODEL returned {len(SCRIPTED_REPLY['tasks'])} tasks -> {len(result.suggestions)} accepted, {result.rejected} rejected")
for s in result.suggestions:
    print(f"  ACCEPTED  {s.start}  {s.description} ({s.duration} min, {s.frequency.value}, {s.priority.name.lower()}) source={s.source}")

print("\nINPUT: model replies with non-JSON garbage on every attempt")
bad = ai_agent.suggest_tasks(pet, llm=lambda p, m: "sorry, I can't do that")
print("  ->", bad.error)

print("\nINPUT: the model API is down")
def down(p, m):
    raise ConnectionError("network down")
print("  ->", ai_agent.suggest_tasks(pet, llm=down).error)
